  // ---------------------------------------------------------------- API

  let lang = 'en';

  function info(code) {
    return LANGS.find((l) => l.code === code) || LANGS[0];
  }

  function setLang(code) {
    lang = S[code] ? code : 'en';
    if (typeof document !== 'undefined' && document.documentElement && document.documentElement.dataset) {
      document.documentElement.dataset.alifaLang = lang;
    }
    return lang;
  }

  function raw(key) {
    const d = S[lang];
    return d && d[key] !== undefined ? d[key] : S.en[key];
  }

  function fill(str, params) {
    return String(str).replace(/\{(\w+)\}/g, (m, k) => (params && params[k] !== undefined && params[k] !== null ? params[k] : m));
  }

  /** Text by key; {param} is replaced with the value from params (not escaped, the caller escapes). */
  function t(key, params) {
    const v = raw(key);
    if (v === undefined) return key;
    return fill(v, params);
  }

  /** Plural by the rules of the language: plural(3, 'plural.orders') -> "3 orders". */
  function plural(n, key, params) {
    const forms = raw(key) || {};
    let cat = 'other';
    try {
      cat = new Intl.PluralRules(info(lang).locale).select(n);
    } catch (e) { /* older environment */ }
    const tpl = forms[cat] !== undefined ? forms[cat] : forms.other;
    return fill(tpl, Object.assign({ n }, params));
  }

  function money(cents, currency) {
    if (cents === null || cents === undefined) return '';
    try {
      return new Intl.NumberFormat(info(lang).locale, { style: 'currency', currency: currency || 'EUR' }).format(cents / 100);
    } catch (e) {
      return (cents / 100).toFixed(2) + ' ' + (currency || 'EUR');
    }
  }

  /** "2026-08-16" -> date in the format of the selected language */
  function date(isoDate) {
    if (!isoDate) return '';
    const [y, m, d] = String(isoDate).split('-').map(Number);
    try {
      return new Intl.DateTimeFormat(info(lang).locale, { day: 'numeric', month: 'numeric', year: 'numeric' }).format(new Date(y, m - 1, d));
    } catch (e) {
      return isoDate;
    }
  }

  /** Translates elements with data-i18n (text), data-i18n-title, data-i18n-placeholder, data-i18n-aria. */
  function apply(rootEl) {
    rootEl.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
    rootEl.querySelectorAll('[data-i18n-title]').forEach((el) => { el.title = t(el.dataset.i18nTitle); });
    rootEl.querySelectorAll('[data-i18n-placeholder]').forEach((el) => { el.placeholder = t(el.dataset.i18nPlaceholder); });
    rootEl.querySelectorAll('[data-i18n-aria]').forEach((el) => { el.setAttribute('aria-label', t(el.dataset.i18nAria)); });
  }

  /** <option> elements for the language select */
  function langOptions(selected) {
    return LANGS.map((l) => `<option value="${l.code}"${l.code === selected ? ' selected' : ''}>${l.name}</option>`).join('');
  }

  return { LANGS, STRINGS: S, setLang, lang: () => lang, t, plural, money, date, apply, langOptions };
